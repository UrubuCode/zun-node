#!/usr/bin/env bash
# Make `cargo` work inside a git worktree nested under `.claude/worktrees/`.
#
# `Cargo.toml` depends on `zun_abi` through the relative path
# `../crates/zun_abi`, which is right for the main checkout (zun-node lives
# inside the Zun repository). From `.claude/worktrees/<name>/` the same path
# resolves to `.claude/worktrees/crates`, which does not exist, and `zun_abi`
# inherits its package fields and lints from the Zun workspace, so it also needs
# a workspace root above it.
#
# This script creates, next to the worktrees (all untracked, local only):
#   * `crates` — a link to the Zun repository's `crates/` directory;
#   * `Cargo.toml` — a one-member workspace for `zun_abi`, carrying the Zun
#     workspace's `[workspace.package]` and `[workspace.lints.*]` sections.
# Each worktree's own `Cargo.toml` declares `[workspace]`, so it stays its own
# root and is not captured by this one.
#
# Usage: tools/setup_worktree_cargo.sh   (from the main zun-node checkout)
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
zun_root="$(cd "$here/.." && pwd)"
dir="$here/.claude/worktrees"
mkdir -p "$dir"

if [ ! -e "$dir/crates" ]; then
  case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*)
      cmd //c mklink //J "$(cygpath -w "$dir/crates")" "$(cygpath -w "$zun_root/crates")" >/dev/null ;;
    *)
      ln -s "$zun_root/crates" "$dir/crates" ;;
  esac
fi

{
  echo '# Generated by tools/setup_worktree_cargo.sh; local only, do not commit.'
  echo '[workspace]'
  echo 'resolver = "2"'
  echo 'members = ["crates/zun_abi"]'
  echo
  awk '/^\[/{keep = ($0 ~ /^\[workspace\.(package|lints)/)} keep' "$zun_root/Cargo.toml"
} > "$dir/Cargo.toml"

echo "worktree cargo setup written to $dir"
